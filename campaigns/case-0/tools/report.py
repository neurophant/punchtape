#!/usr/bin/env python3
"""report.py — the wave report of the case-0 campaign, one
command (the 0.2.0 report): the tables of hands / operators /
layers printed on the DOUBLE TOKEN BASE (the double-base law: in+out AND
total = in+out+cache_read side by side; the $ column stays
cache-aware), the deltas with honest multiples (the §0.2b.3
discipline: every multiple prints, never rounded to the favorable
side), the proofs of identical conditions, the red-line summary.
Numbers come only from the captured files and the platform db
ledger; nothing is retyped.

  report.py <run-root> --prices prices.json --models models.json \
      --out wave-report.md [--glue <analytics.md> --glue-out <dir|file>]

The GLUE (the owner saw a stale table in docs/ because the glue
was a manual cat): with --glue the tool ALSO
writes the session report itself — the core (the same bytes as
--out) followed by the analytics file — to --glue-out (a directory
receives case0-<UTC>-<sense>-session-report.md, the sense parsed
from the run root's name); no manual concatenation exists anywhere.
The glue is REGENERATED by every report.py run that carries --glue.
"""
import argparse
import datetime
import glob
import json
import os
import re
import sys


def jload(path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None


def fmt(v, nd=2):
    if v is None:
        return "—"
    if isinstance(v, float):
        return ("%0.*f" % (nd, v))
    return str(v)


def mult(a, b):
    """The honest multiple a/b ('how many times'); None when unknown;
    a defeat prints the same way, never rounded favorably."""
    if a is None or b is None or b == 0:
        return None
    return a / b


def cost(in_tok, out_tok, cache, rates):
    if not rates:
        return None
    pin, pout = rates.get("in"), rates.get("out")
    pcache = rates.get("cached_in", rates.get("in"))
    return round((in_tok - cache) * pin / 1e6 + cache * pcache / 1e6
                 + out_tok * pout / 1e6, 4)


def cache_share(c):
    """cache_read as % of total tokens (the acceptance law:
    machine hands ≥ 65%); None — unknown."""
    p = c["platform"] or {}
    tot = p.get("tokens_total")
    cache = p.get("tokens_cache_read")
    if not tot:
        return None
    return 100.0 * (cache or 0) / tot


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_root")
    ap.add_argument("--prices", required=True)
    ap.add_argument("--models", default=None,
                    help="model_id -> tier map (the platform names)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--glue", default=None,
                    help="the analytics layer to concatenate after the core")
    ap.add_argument("--glue-out", default=None,
                    help="where the glued session report lands (a directory "
                         "gets case0-<UTC>-<sense>-session-report.md)")
    args = ap.parse_args()

    root = os.path.abspath(args.run_root)
    prices = (jload(args.prices) or {}).get("per_million", {})
    models = jload(args.models) if args.models else None
    modmap = {}
    if models and "map" in models:
        for e in models["map"]:
            modmap[e.get("model_id")] = e.get("tier")

    def rates_of(model):
        if model in prices:
            return prices[model]
        tier = modmap.get(model)
        rates = prices.get(tier) if tier else None
        if rates is None and len(prices) == 1:
            # the campaign prices exactly one tier
            # (both hands run the same model) — a missing model row
            # in the ledger slice must not zero the $ column
            rates = next(iter(prices.values()))
        return rates

    ledger = (jload(os.path.join(root, "usage", "ledger.json")) or {}).get("agents") or {}
    cells = []
    for m in sorted(glob.glob(os.path.join(root, "manifests", "*.json"))):
        man = jload(m)
        if not man:
            continue
        ev = os.path.join(root, "tasks", man["cell"], "evidence")
        cells.append({
            "man": man,
            "meta": jload(os.path.join(ev, "meta.json")),
            "platform": jload(os.path.join(ev, "platform.json")),
            "operator": jload(os.path.join(ev, "operator.json")),
            "summary": jload(os.path.join(ev, "summary.json")),
            "judge": jload(os.path.join(ev, "judge.json")),
            "evidence": jload(os.path.join(ev, "evidence.json")),
            "findings": jload(os.path.join(ev, "findings.json")),
            "measure": jload(os.path.join(ev, "measure.json")),
            "metrics": jload(os.path.join(root, "tasks", man["cell"], "metrics.json")),
        })

    tasks = {}
    for c in cells:
        k = (c["man"]["sense"], c["man"]["stack"])
        tasks.setdefault(k, {})[c["man"]["hand"]] = c

    L = []
    w = L.append
    w("# Wave report (case-0) — %s" % os.path.basename(root))
    w("")
    w("Protocol 0.2.0 on the host world; the DOUBLE TOKEN BASE (the")
    w("double-base law): `in+out` (the 0.2.0 working base) and `total` (= in+out+cache_read)")
    w("side by side in every table; the `$` column is cache-aware. Numbers come")
    w("only from the platform db ledger and the captured cell files.")
    w("")

    # --- 1. proofs of identical conditions and no cheating
    w("## 1. Identical conditions and no cheating")
    w("")
    violations = []
    for (sense, stack), hands in sorted(tasks.items()):
        briefs = {h: (c["evidence"] or {}).get("brief_sha256")
                  for h, c in hands.items() if c["evidence"]}
        if len(briefs) > 1 and len(set(briefs.values())) > 1:
            violations.append(f"{sense}-{stack}: brief digests diverge: {briefs}")
        mats = {h: json.dumps((c["evidence"] or {}).get("materials"), sort_keys=True)
                for h, c in hands.items() if c["evidence"]}
        if len(mats) > 1 and len(set(mats.values())) > 1:
            violations.append(f"{sense}-{stack}: materials diverge")
        bins = {h: (c["evidence"] or {}).get("punchtape_binary_sha256")
                for h, c in hands.items() if c["evidence"]}
        if "solo" in bins and bins["solo"] is not None:
            violations.append(f"{sense}-{stack}: the solo hand carries a binary")
        runbins = {c["man"].get("binary_sha256") for c in hands.values()}
        if len(runbins - {None}) > 1:
            violations.append(f"{sense}-{stack}: the run's binary sha diverges: {runbins}")
    for c in cells:
        ev = c["evidence"] or {}
        cell = c["man"]["cell"]
        for m, after in (ev.get("materials_after") or {}).items():
            if (ev.get("materials") or {}).get(m) != after:
                violations.append(f"{cell}: material {m} changed")
        if ev.get("canary_leaks"):
            violations.append(f"{cell}: CANARY LEAK: {ev['canary_leaks']}")
        if ev.get("transcript_scan"):
            violations.append(f"{cell}: TRANSCRIPT SCAN HIT: {ev['transcript_scan']}")
        if ev.get("product_scan"):
            violations.append(f"{cell}: PRODUCT SCAN HIT: {ev['product_scan']}")
    # the red lines of the run
    redlines = []
    rlp = os.path.join(root, "redlines.jsonl")
    if os.path.isfile(rlp):
        for line in open(rlp, encoding="utf-8"):
            if line.strip():
                d = json.loads(line)
                if d.get("disposition") is None:
                    redlines.append(d)
    if redlines:
        violations.append(f"{len(redlines)} undispositioned red line(s) (redlines.jsonl)")
    if violations:
        w("**RED LINES:**")
        for v in violations:
            w("- " + v)
    else:
        w("Brief/materials identical for every hand of every task; one binary sha")
        w("for the run (solo carries none); materials unchanged after the finish;")
        w("canaries intact; transcript/product scans empty; no undispositioned red")
        w("lines — **clean**.")
    w("")

    # --- 2. the hands table (METRICS.md structure, double base)
    w("## 2. Hands (time = active seconds, db ledger; tokens on both bases)")
    w("")
    w("| cell | hand | time, s | in+out | total (incl cache) | cache | cache% | tools | $ | suite / deliverables | submissions ±/− | verb-wall, s | verdict |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for c in cells:
        p = c["platform"] or {}
        m = c["metrics"] or {}
        mach = m.get("machine") or {}
        s = c["summary"] or {}
        meas = c["measure"] or {}
        rates = rates_of(p.get("model"))
        c_ = cost(p.get("tokens_in") or 0, p.get("tokens_out") or 0,
                  p.get("tokens_cache_read") or 0, rates)
        suite = meas.get("suite_double_green")
        suite_s = ("×2 green" if suite else ("not green×2" if meas else "—"))
        if meas.get("deliverables_count") is not None:
            suite_s += f", deliv. {meas['deliverables_count']}/5"
        subs = "—" if c["man"]["hand"] == "solo" else \
            f"{mach.get('submissions_accepted', 0)}/{mach.get('submissions_rejected', 0)}"
        vw = (mach.get("verb_wall_ms") or 0) / 1000.0
        if c["man"]["hand"] == "solo":
            vw = None
        w("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            c["man"]["cell"], c["man"]["hand"],
            fmt(p.get("elapsed_s"), 1),
            fmt(p.get("tokens_inout"), 0), fmt(p.get("tokens_total"), 0),
            fmt(p.get("tokens_cache_read"), 0), fmt(cache_share(c), 0),
            fmt(p.get("tool_calls"), 0),
            fmt(c_),
            suite_s, subs,
            fmt(vw, 1) if vw is not None else "—",
            (s.get("ruling") or "—")[:60] if s.get("ruling") else "—"))
    w("")
    w("cache% = cache_read ÷ total (machine hands")
    w("≥ 65%).")
    w("")

    # --- 2a. the uniform per-hand tables (the uniform format;
    # the owner's law: one table PER TASK + the
    # ALL-hands table of the whole run — every wave prints these)
    def cov_short(meas):
        c = (meas.get("coverage_tooling") or "—")
        return c if len(c) <= 60 else c[:57] + "…"

    def uniform_row(c):
        p = c["platform"] or {}
        m = c["metrics"] or {}
        mach = m.get("machine") or {}
        s = c["summary"] or {}
        meas = c["measure"] or {}
        o = c["operator"] or {}
        rates = rates_of(p.get("model"))
        hand_d = cost(p.get("tokens_in") or 0, p.get("tokens_out") or 0,
                      p.get("tokens_cache_read") or 0, rates)
        op_d = cost(o.get("tokens_in") or 0, o.get("tokens_out") or 0,
                    o.get("tokens_cache_read") or 0, rates) \
            if o.get("tokens_in") is not None else 0.0
        if c["man"]["hand"] == "solo":
            subs = vw = prose = "—"
            cases = "own suite"
        else:
            subs = "%d/%d" % (mach.get("submissions_accepted", 0),
                              mach.get("submissions_rejected", 0))
            vw = fmt((mach.get("verb_wall_ms") or 0) / 1000.0, 1)
            cases = "%s/%s" % (s.get("cases_pass"), s.get("cases_total"))
            prose = "%s/%s" % (s.get("describes"), s.get("capabilities"))
        suite2 = "green×2" if meas.get("suite_double_green") else \
            ("not ×2" if meas else "—")
        dg = meas.get("deliverables_count")
        dg = "%s/5" % dg if dg is not None else "—"
        waits = p.get("decision_wait_s") or []
        wait_s = "%.0f" % max(waits) if waits else "—"
        # the operator triple rides ONE header column ($ / decisions / wait)
        op_cell = "%s / %s / %s" % (fmt(op_d), fmt(o.get("decisions"), 0), wait_s)
        return "| %s | %s | %s/%s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            c["man"]["cell"], fmt(p.get("elapsed_s"), 1),
            fmt(p.get("tokens_in"), 0), fmt(p.get("tokens_out"), 0),
            fmt(hand_d), subs, vw,
            (s.get("ruling") or "—")[:44] if s.get("ruling") else "—",
            cases, suite2, dg, prose, cov_short(meas), fmt(s.get("loc"), 0),
            op_cell)

    UNI_HEAD = ("| hand | time, s | tokens in/out | hand $ | submissions ±/− | "
                "verb-wall, s | verdict | cases | suite×2 | "
                "deliv. | prose | coverage | LOC | operator $ / decisions / wait, s |")
    UNI_SEP = "|" + "---|" * 15
    w("## 2a. Uniform per-hand tables (the 0.2.0 METRICS wave-S format:")
    w("one table PER TASK, then ALL hands of ALL tasks — the report contract")
    w("of METHODOLOGY §I.11; $ cache-aware per prices.json")
    w("")
    for (sense, stack) in sorted(tasks):
        w("### %s-%s" % (sense, stack))
        w("")
        w(UNI_HEAD)
        w(UNI_SEP)
        for h in ("solo", "top"):
            c = tasks[(sense, stack)].get(h)
            if c:
                w(uniform_row(c))
        w("")
    w("### ALL hands of ALL tasks")
    w("")
    w(UNI_HEAD)
    w(UNI_SEP)
    for c in cells:
        w(uniform_row(c))
    w("")

    # --- 3. operators (separate accounting, never summed with hands)
    w("## 3. Operators (separate accounting; the 0.2.0 hard rule)")
    w("")
    w("| cell | hand | time, s | in+out | total | decisions |")
    w("|---|---|---|---|---|---|")
    op_side = {"solo": {"s": 0.0, "inout": 0, "total": 0, "n": 0},
               "top": {"s": 0.0, "inout": 0, "total": 0, "n": 0}}
    for c in cells:
        o = c["operator"] or {}
        ino = (o.get("tokens_in") or 0) + (o.get("tokens_out") or 0)
        tot = ino + (o.get("tokens_cache_read") or 0)
        w("| %s | %s | %s | %s | %s | %s |" % (
            c["man"]["cell"], c["man"]["hand"], fmt(o.get("elapsed_s"), 1),
            fmt(ino, 0) if o.get("elapsed_s") is not None else "—",
            fmt(tot, 0) if o.get("elapsed_s") is not None else "—",
            fmt(o.get("decisions"), 0)))
        if o.get("elapsed_s") is not None:
            s = op_side[c["man"]["hand"]]
            s["s"] = round(s["s"] + o["elapsed_s"], 1)
            s["inout"] += ino
            s["total"] += tot
            s["n"] += o.get("decisions") or 0
    # Σ operators BY HAND SIDE (the owner's demand: the summary
    # must carry each side's operator
    # sums — the camp economics live on this asymmetry)
    w("| **Σ operators solo** | solo | %s | %s | %s | %s |" % (
        fmt(op_side["solo"]["s"], 1), fmt(op_side["solo"]["inout"], 0),
        fmt(op_side["solo"]["total"], 0), fmt(op_side["solo"]["n"], 0)))
    w("| **Σ operators top (machine)** | top | %s | %s | %s | %s |" % (
        fmt(op_side["top"]["s"], 1), fmt(op_side["top"]["inout"], 0),
        fmt(op_side["top"]["total"], 0), fmt(op_side["top"]["n"], 0)))
    w("")

    # --- 4. layers (judges, measurers — methodology overhead)
    w("## 4. Layers (judges, measurers — methodology overhead, not the product path)")
    w("")
    w("| layer | time, s | in+out | total |")
    w("|---|---|---|---|")
    layer_rows = {}
    for aid, e in sorted(ledger.items()):
        roles = e.get("roles") or []
        for r in roles:
            if r in ("judge", "measurer"):
                cells_of = e.get("cells") or ["?"]
                key = f"{r}/{'/'.join(sorted(cells_of))}"
                row = layer_rows.setdefault(key, {"s": 0.0, "inout": 0, "total": 0})
                row["s"] = round(row["s"] + (e.get("active_s") or 0), 1)
                inout = (e.get("input_tokens") or 0) + (e.get("output_tokens") or 0)
                row["inout"] += inout
                row["total"] += inout + (e.get("cache_tokens") or 0)
    if layer_rows:
        for k in sorted(layer_rows):
            r = layer_rows[k]
            w(f"| {k} | {fmt(r['s'], 1)} | {fmt(r['inout'], 0)} | {fmt(r['total'], 0)} |")
    else:
        w("(no judge/measurer agents in the ledger yet)")
    w("")

    # --- 5. deltas with honest multiples (both bases)
    # (the owner's word: TWO hands —
    #  solo and top; the weak column and its multiples are gone)
    w("## 5. Deltas — what the machine buys (both token bases, §0.2b.3 multiples)")
    w("")
    w("| task | metric | solo | top | solo/top |")
    w("|---|---|---|---|---|")

    def hand_facts(hands, h):
        c = hands.get(h)
        if not c:
            return None
        p = c["platform"] or {}
        return {"s": p.get("elapsed_s"), "inout": p.get("tokens_inout"),
                "total": p.get("tokens_total")}

    agg = {}
    for (sense, stack), hands in sorted(tasks.items()):
        f = {h: hand_facts(hands, h) for h in ("solo", "top")}
        for met in ("s", "inout", "total"):
            row = [f[h][met] if f[h] else None for h in ("solo", "top")]
            m1 = mult(row[0], row[1])
            w("| %s-%s | %s | %s | %s | %s |" % (
                sense, stack, {"s": "time, s", "inout": "in+out",
                               "total": "total"}[met],
                fmt(row[0], 1 if met == "s" else 0),
                fmt(row[1], 1 if met == "s" else 0),
                fmt(m1, 2) if m1 is not None else "—"))
            a, b = row[0], row[1]
            if a is not None and b is not None:
                agg.setdefault("solo/top", {}).setdefault(met, []).append((a, b))
    w("")
    for pair in sorted(agg):
        for met in ("s", "inout", "total"):
            vals = agg[pair].get(met) or []
            if vals:
                sums = [sum(x for x, _ in vals), sum(y for _, y in vals)]
                w(f"- {pair} Σ{ {'s': 'time', 'inout': 'in+out', 'total': 'total'}[met] }: "
                  f"{sums[0]} vs {sums[1]} — multiple {fmt(mult(sums[0], sums[1]), 2)}")
    w("")

    # --- 6. camp sums (every hand WITH its operator: time AND tokens,
    # both bases; the §0.2b.1 camp level — the owner's law:
    # uniform, per task + the Σ row, in every wave report)
    w("## 6. Camp sums — every hand with its operator (time and tokens,")
    w("both bases; camp = the hand + its operator, §0.2b.1)")
    w("")
    w("| task | hand | hand, s | oper, s | camp, s | hand in+out | oper in+out | camp in+out | hand total | oper total | camp total |")
    w("|---|---|---|---|---|---|---|---|---|---|---|")
    camp_tot = {"s": [0.0, 0.0], "io": [0, 0], "tot": [0, 0],
                "hand_s": [0.0, 0.0], "hand_io": [0, 0], "hand_tot": [0, 0],
                "oper_s": [0.0, 0.0], "oper_io": [0, 0], "oper_tot": [0, 0]}
    for (sense, stack) in sorted(tasks):
        camp = {}
        for h in ("solo", "top"):
            c = tasks[(sense, stack)].get(h)
            if not c:
                continue
            p = c["platform"] or {}
            o = c["operator"] or {}
            ph = p.get("elapsed_s") or 0.0
            po = o.get("elapsed_s") or 0.0
            ih = (p.get("tokens_in") or 0) + (p.get("tokens_out") or 0)
            io_ = (o.get("tokens_in") or 0) + (o.get("tokens_out") or 0)
            th = ih + (p.get("tokens_cache_read") or 0)
            to_ = io_ + (o.get("tokens_cache_read") or 0)
            camp[h] = (ph, po, ph + po, ih, io_, ih + io_, th, to_, th + to_)
            i = 0 if h == "solo" else 1
            camp_tot["s"][i] += ph + po
            camp_tot["io"][i] += ih + io_
            camp_tot["tot"][i] += th + to_
            camp_tot["hand_s"][i] += ph
            camp_tot["hand_io"][i] += ih
            camp_tot["hand_tot"][i] += th
            camp_tot["oper_s"][i] += po
            camp_tot["oper_io"][i] += io_
            camp_tot["oper_tot"][i] += to_
            w("| %s-%s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                sense, stack, h, fmt(ph, 1), fmt(po, 1), fmt(ph + po, 1),
                fmt(ih, 0), fmt(io_, 0), fmt(ih + io_, 0),
                fmt(th, 0), fmt(to_, 0), fmt(th + to_, 0)))
        if "solo" in camp and "top" in camp:
            s, t = camp["solo"], camp["top"]
            m_s = mult(s[2], t[2])
            m_io = mult(s[5], t[5])
            m_t = mult(s[8], t[8])
            if t[2] < s[2] and t[5] < s[5] and t[8] < s[8]:
                g1 = "top (G1)"
            elif s[2] < t[2] and s[5] < t[5] and s[8] < t[8]:
                g1 = "solo (G1)"
            else:
                g1 = "— (exchange)"
            w("| %s-%s | solo/top × (%s) | — | — | %s | — | — | %s | — | — | %s |" % (
                sense, stack, g1, fmt(m_s, 2), fmt(m_io, 2), fmt(m_t, 2)))
    # Σ rows BY SIDE, every cell its own true number exactly once
    # (the owner's law: no unfilled cells AND no copy-paste
    # duplication — the hand sums live in the hand columns, the
    # operator sums in the operator columns, the camp sums in the camp
    # columns; the × row is the true ratio of EVERY column)
    for i, side in ((0, "solo"), (1, "top")):
        hs, os_ = camp_tot["hand_s"][i], camp_tot["oper_s"][i]
        hio, oio = camp_tot["hand_io"][i], camp_tot["oper_io"][i]
        ht, ot = camp_tot["hand_tot"][i], camp_tot["oper_tot"][i]
        w("| **Σ camps %s (hands, oper, camp)** | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
            side, side, fmt(hs, 1), fmt(os_, 1), fmt(hs + os_, 1),
            fmt(hio, 0), fmt(oio, 0), fmt(hio + oio, 0),
            fmt(ht, 0), fmt(ot, 0), fmt(ht + ot, 0)))
    w("| **Σ solo/top ×** | — | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
        fmt(mult(camp_tot["hand_s"][0], camp_tot["hand_s"][1]), 2),
        fmt(mult(camp_tot["oper_s"][0], camp_tot["oper_s"][1]), 2),
        fmt(mult(camp_tot["s"][0], camp_tot["s"][1]), 2),
        fmt(mult(camp_tot["hand_io"][0], camp_tot["hand_io"][1]), 2),
        fmt(mult(camp_tot["oper_io"][0], camp_tot["oper_io"][1]), 2),
        fmt(mult(camp_tot["io"][0], camp_tot["io"][1]), 2),
        fmt(mult(camp_tot["hand_tot"][0], camp_tot["hand_tot"][1]), 2),
        fmt(mult(camp_tot["oper_tot"][0], camp_tot["oper_tot"][1]), 2),
        fmt(mult(camp_tot["tot"][0], camp_tot["tot"][1]), 2)))
    w("")

    # --- 7. comparability
    w("## 7. Comparability")
    w("")
    methods = sorted({(c["measure"] or {}).get("suite_method") for c in cells
                      if (c["measure"] or {}).get("suite_method")})
    if len(methods) == 1:
        w(f"Every hand's suite ran under one procedure (method line: \"{methods[0]}\").")
    elif methods:
        w("Suite method lines: %s" % "; ".join(str(m) for m in methods))
    else:
        w("(no measure.json captured yet)")
    w("Deliverables are counted by one script with a recorded method line; the")
    w("machine hands' corpus replay runs through the campaign's own runner")
    w("(tools/case-runner-host.py) — the same procedure for every product.")
    w("")

    # --- 7. findings registry
    w("## 8. Problems, pains and findings registry")
    w("")
    seen = 0
    for c in cells:
        for f in (c["findings"] or []):
            w("- [%s] %s: %s" % (f.get("kind", "?"), c["man"]["cell"],
                                 f.get("text", "")))
            seen += 1
    if not seen:
        w("(no findings)")

    out = "\n".join(L) + "\n"
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(out)
    print(out)

    # the GLUE (no manual cat anywhere):
    # core + analytics, written by the tool itself; a directory target
    # names the file case0-<UTC>-<sense>-session-report.md with the
    # sense parsed from the run root's name (…-case0-<sense>)
    if args.glue and args.glue_out:
        if not os.path.isfile(args.glue):
            print(f"REPORT GLUE: analytics file missing: {args.glue}",
                  file=sys.stderr)
            sys.exit(2)
        analytics = open(args.glue, encoding="utf-8").read()
        if not analytics.endswith("\n"):
            analytics += "\n"
        target = args.glue_out
        if os.path.isdir(target):
            m = re.search(r"-case0-(.+)$", os.path.basename(
                os.path.normpath(args.run_root)))
            sense = m.group(1) if m else "wave"
            ts = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
            target = os.path.join(target, f"case0-{ts}-{sense}-session-report.md")
        os.makedirs(os.path.dirname(os.path.abspath(target)) or ".",
                    exist_ok=True)
        with open(target, "w", encoding="utf-8") as f:
            f.write(out + "\n" + analytics)
        print(f"glued session report: {target}", file=sys.stderr)


